import { useState } from 'react';
import { Copy, Download, Check, Sparkles, Code2 } from 'lucide-react';
import { useAnalysis } from '../context/AnalysisContext';

export default function ReportsPage() {
  const { reports, analysisData } = useAnalysis();
  const [activeTab, setActiveTab] = useState('executive');
  const [copied, setCopied] = useState(false);

  const currentReportContent =
    activeTab === 'executive' ? reports.executive : reports.technical;

  const handleCopy = () => {
    navigator.clipboard.writeText(currentReportContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const filename = `${analysisData?.filename || 'nerve_analysis'}_${activeTab}_report.md`;
    const blob = new Blob([currentReportContent], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {/* Report Header Bar */}
      <div className="bg-white rounded-xl border border-slate-200 shadow-xs p-4 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
        {/* Tab switcher */}
        <div className="flex items-center space-x-1 bg-slate-100 p-1 rounded-lg text-xs">
          <button
            onClick={() => setActiveTab('executive')}
            className={`inline-flex items-center space-x-1.5 px-3 py-1.5 rounded-md font-semibold transition ${
              activeTab === 'executive'
                ? 'bg-white text-slate-900 shadow-2xs'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <Sparkles className="w-3.5 h-3.5 text-indigo-600" />
            <span>Executive Summary</span>
          </button>

          <button
            onClick={() => setActiveTab('technical')}
            className={`inline-flex items-center space-x-1.5 px-3 py-1.5 rounded-md font-semibold transition ${
              activeTab === 'technical'
                ? 'bg-white text-slate-900 shadow-2xs'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <Code2 className="w-3.5 h-3.5 text-slate-600" />
            <span>Technical Report with Citations</span>
          </button>
        </div>

        {/* Action buttons */}
        <div className="flex items-center space-x-2 text-xs">
          <button
            onClick={handleCopy}
            className="inline-flex items-center space-x-1.5 px-3 py-1.5 rounded-lg border border-slate-200 bg-white hover:bg-slate-50 text-slate-700 transition"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-600" />
                <span className="text-emerald-700 font-semibold">Copied Markdown</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5" />
                <span>Copy Markdown</span>
              </>
            )}
          </button>

          <button
            onClick={handleDownload}
            className="inline-flex items-center space-x-1.5 px-3 py-1.5 rounded-lg bg-indigo-600 hover:bg-indigo-700 text-white font-medium shadow-2xs transition"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download .MD</span>
          </button>
        </div>
      </div>

      {/* Report Content Body */}
      <div className="bg-white rounded-xl border border-slate-200 shadow-xs p-6 md:p-8">
        <div className="max-w-4xl mx-auto">
          <div className="border-b border-slate-100 pb-4 mb-6 flex items-center justify-between text-xs text-slate-400">
            <span>
              Generated by Nerve Agentic Security Writer (Citations format: <code className="font-mono text-indigo-600 bg-indigo-50 px-1 py-0.5 rounded">[E-xxxx]</code>)
            </span>
            <span className="font-mono">
              Target: {analysisData?.metadata?.package_name || analysisData?.filename}
            </span>
          </div>

          <pre className="text-sm font-sans text-slate-800 whitespace-pre-wrap leading-relaxed tracking-normal select-text">
            {currentReportContent}
          </pre>
        </div>
      </div>
    </div>
  );
}
